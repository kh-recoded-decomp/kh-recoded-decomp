#include "src/overlays/ov001/ActorBoxDisplayList.h"

enum {
    GX_NOP = 0x00,
    GX_COLOR = 0x20,
    GX_VERTEX16 = 0x23,
    GX_VERTEX_XY = 0x25,
    GX_VERTEX_XZ = 0x26,
    GX_VERTEX_YZ = 0x27,
    GX_POLYGON_ATTR = 0x29,
    GX_TEXTURE_PARAM = 0x2a,
    GX_BEGIN = 0x40,
    GX_END = 0x41,
    GX_QUADS = 1,
    BOX_HALF = 0x800,
    BOX_BOTTOM = -0x1000
};

#define COMMANDS(a, b, c, d) ((u32)(a) | ((u32)(b) << 8) | ((u32)(c) << 16) | ((u32)(d) << 24))
#define POSITION_PAIR(a, b) ((u32)(u16)(a) | ((u32)(u16)(b) << 16))

/* Both passes use the same six faces, centered on X/Z and extending below Y=0. */
#define BOX_COMMANDS { \
    { \
        {COMMANDS(GX_BEGIN, GX_COLOR, GX_VERTEX16, GX_VERTEX_XZ), \
         {GX_QUADS, 0, POSITION_PAIR(-BOX_HALF, 0), (u16)-BOX_HALF, POSITION_PAIR(-BOX_HALF, BOX_HALF)}}, \
        {COMMANDS(GX_VERTEX_XZ, GX_VERTEX_XZ, GX_VERTEX16, GX_VERTEX_XZ), \
         {POSITION_PAIR(BOX_HALF, BOX_HALF), POSITION_PAIR(BOX_HALF, -BOX_HALF), \
          POSITION_PAIR(-BOX_HALF, BOX_BOTTOM), (u16)-BOX_HALF, POSITION_PAIR(BOX_HALF, -BOX_HALF)}}, \
        {COMMANDS(GX_VERTEX_XZ, GX_VERTEX_XZ, GX_VERTEX16, GX_VERTEX_XY), \
         {POSITION_PAIR(BOX_HALF, BOX_HALF), POSITION_PAIR(-BOX_HALF, BOX_HALF), \
          POSITION_PAIR(-BOX_HALF, BOX_BOTTOM), (u16)-BOX_HALF, POSITION_PAIR(-BOX_HALF, 0)}}, \
        {COMMANDS(GX_VERTEX_XY, GX_VERTEX_XY, GX_VERTEX16, GX_VERTEX_XY), \
         {POSITION_PAIR(BOX_HALF, 0), POSITION_PAIR(BOX_HALF, BOX_BOTTOM), \
          POSITION_PAIR(-BOX_HALF, BOX_BOTTOM), (u16)BOX_HALF, POSITION_PAIR(BOX_HALF, BOX_BOTTOM)}}, \
        {COMMANDS(GX_VERTEX_XY, GX_VERTEX_XY, GX_VERTEX16, GX_VERTEX_YZ), \
         {POSITION_PAIR(BOX_HALF, 0), POSITION_PAIR(-BOX_HALF, 0), \
          POSITION_PAIR(-BOX_HALF, BOX_BOTTOM), (u16)-BOX_HALF, POSITION_PAIR(BOX_BOTTOM, BOX_HALF)}}, \
        {COMMANDS(GX_VERTEX_YZ, GX_VERTEX_YZ, GX_VERTEX16, GX_VERTEX_YZ), \
         {POSITION_PAIR(0, BOX_HALF), POSITION_PAIR(0, -BOX_HALF), \
          POSITION_PAIR(BOX_HALF, BOX_BOTTOM), (u16)-BOX_HALF, POSITION_PAIR(0, -BOX_HALF)}} \
    }, \
    COMMANDS(GX_VERTEX_YZ, GX_VERTEX_YZ, GX_END, GX_NOP), \
    {POSITION_PAIR(0, BOX_HALF), POSITION_PAIR(BOX_BOTTOM, BOX_HALF)}, \
    GX_NOP \
}

ActorBoxDisplayList gActorBoxDisplayList = {
    COMMANDS(GX_TEXTURE_PARAM, GX_POLYGON_ATTR, GX_NOP, GX_NOP),
    0,
    0x00080070,
    BOX_COMMANDS,
    COMMANDS(GX_POLYGON_ATTR, GX_NOP, GX_NOP, GX_NOP),
    0x3f0800b0,
    BOX_COMMANDS
};
